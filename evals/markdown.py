"""PR-comment-ready Markdown summaries for runs and comparisons."""
from __future__ import annotations

from typing import List

from .compare import Comparison
from .models import CaseResult, SuiteResult


def one_line_reason(case: CaseResult) -> str:
    """Short human-readable reason a case failed, errored, or is flaky."""
    if case.flaky and case.pass_rate is not None:
        return f"flaky: passed {case.pass_rate * 100:.0f}% of {case.repeat_runs} repeats"
    if case.error:
        return f"error: {case.error}"
    if case.checks_failed:
        first = case.checks_failed[0]
        detail = first.get("detail", "") if isinstance(first, dict) else str(first)
        check = first.get("check", "") if isinstance(first, dict) else ""
        reason = f"{check}: {detail}".strip(": ")
        return reason[:160]
    if case.judge is not None and not case.judge.passed:
        return (
            f"judge score {case.judge.score:.1f}/10 below threshold "
            f"{case.judge.threshold:.1f}"
        )
    return "status: " + case.status


def markdown_for_run(result: SuiteResult) -> str:
    """Markdown summary of one suite run, ready to paste as a PR comment."""
    s = result.summary()
    lines = [
        f"# Eval results: {result.suite_name}",
        "",
        f"Agent `{result.agent_name}` - pass rate **{s['pass_rate']}%** "
        f"({s['passed']}/{s['total']} passed, {s['failed']} failed, {s['errors']} errors).",
        f"Total estimated judge cost: **${s['total_cost_usd']:.4f}** "
        f"({s['total_tokens']:,} tokens).",
        f"Latency: mean {s['mean_latency_ms']} ms, p50 {s['p50_latency_ms']} ms, "
        f"p95 {s['p95_latency_ms']} ms.",
        "",
    ]

    flaky = [c for c in result.cases if c.flaky]
    if flaky:
        lines.append(f"## Flaky cases ({len(flaky)})")
        for c in flaky:
            lines.append(f"- `{c.name}` - {one_line_reason(c)}")
        lines.append("")

    bad = [c for c in result.cases if c.status in ("fail", "error")]
    if bad:
        lines.append(f"## Failing cases ({len(bad)})")
        for c in bad:
            lines.append(f"- `{c.name}` ({c.status}) - {one_line_reason(c)}")
        lines.append("")
    else:
        lines.append("All cases passed. No failures to report.")
        lines.append("")

    lines.append(f"_Generated by agent-evals from `{result.suite_name}`._")
    return "\n".join(lines)


def _fmt_score(v) -> str:
    return f"{v:.1f}" if v is not None else "n/a"


def markdown_for_compare(comparison: Comparison) -> str:
    """Markdown summary of a comparison, ready to paste as a PR comment."""
    s = comparison.summary
    lines = [
        f"# Eval comparison: {comparison.name_a} vs {comparison.name_b}",
        "",
        f"**{s['improved']}** improved, **{s['regressed']}** regressed, "
        f"**{s['unchanged']}** unchanged "
        f"({s['newly_passing']} newly passing, {s['newly_failing']} newly failing).",
        "",
    ]

    regressions = [
        d for d in comparison.sorted_by_regression() if d.delta is not None and d.delta < 0
    ]
    improvements = [
        d
        for d in comparison.sorted_by_regression()
        if d.delta is not None and d.delta > 0
    ]

    if regressions:
        lines.append(f"## Top regressions ({len(regressions)})")
        for d in regressions[:10]:
            lines.append(
                f"- `{d.name}`: {_fmt_score(d.score_b)} -> {_fmt_score(d.score_a)} "
                f"(delta {d.delta:+.1f})"
            )
        lines.append("")
    if improvements:
        lines.append(f"## Top improvements ({len(improvements)})")
        for d in reversed(improvements[-10:]):
            lines.append(
                f"- `{d.name}`: {_fmt_score(d.score_b)} -> {_fmt_score(d.score_a)} "
                f"(delta {d.delta:+.1f})"
            )
        lines.append("")

    newly_failing = comparison.by_class("newly_failing")
    newly_passing = comparison.by_class("newly_passing")
    if newly_failing:
        lines.append(f"## Newly failing ({len(newly_failing)})")
        for d in newly_failing:
            lines.append(f"- `{d.name}` ({d.status_b} -> {d.status_a})")
        lines.append("")
    if newly_passing:
        lines.append(f"## Newly passing ({len(newly_passing)})")
        for d in newly_passing:
            lines.append(f"- `{d.name}` ({d.status_b} -> {d.status_a})")
        lines.append("")

    missing = comparison.by_class("only_in_a") + comparison.by_class("only_in_b")
    if missing:
        lines.append(f"## Cases only in one run ({len(missing)})")
        for d in missing:
            where = comparison.name_a if d.classification == "only_in_a" else comparison.name_b
            lines.append(f"- `{d.name}` (only in {where})")
        lines.append("")

    if not regressions and not improvements and not newly_failing and not newly_passing:
        lines.append("No score changes between the two runs.")
        lines.append("")

    lines.append("_Generated by agent-evals compare._")
    return "\n".join(lines)


def write_markdown(text: str, path) -> str:
    from pathlib import Path

    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text + "\n", encoding="utf-8")
    return str(p)
